import test from 'node:test'
import assert from 'node:assert/strict'
import { createUiStore } from '../src/ui/store.js'

test('completion review has a live phase that clears on settlement and cancellation', () => {
  const store = createUiStore()
  store.dispatch({ type: 'status', text: 'running' })
  store.dispatch({ type: 'completion.assessment.start' })
  assert.equal(store.getState().activity.phase, 'verifying')
  store.dispatch({ type: 'completion.assessment.end', outcome: 'continue' })
  assert.equal(store.getState().activity.phase, 'running')
  store.dispatch({ type: 'status', text: 'interrupted' })
  assert.equal(store.getState().activity, null)
})

test('UI stores isolate instances and preserve snapshots across streaming and queue delivery', () => {
  const first = createUiStore()
  const second = createUiStore()
  first.dispatch({ type: 'ui.language', language: 'zh-CN' })
  assert.equal(second.getState().language, 'en')
  first.dispatch({ type: 'queued', inputId: 'input', delivery: 'steer', text: 'task' })
  first.dispatch({ type: 'assistant.start', stepId: 'step' })
  const before = first.getState()
  first.dispatch({ type: 'assistant.delta', stepId: 'step', text: 'hello' })
  assert.equal(before.streams.get('step'), '')
  assert.equal(first.getState().streams.get('step'), 'hello')
  first.dispatch({ type: 'user', inputId: 'input', text: 'task' })
  assert.equal(before.queued.has('input'), true)
  assert.equal(first.getState().queued.size, 0)
  first.dispatch({ type: 'assistant.end', stepId: 'step' })
  first.dispatch({ type: 'assistant.delta', stepId: 'step', text: 'late' })
  assert.equal(first.getState().streams.size, 0)
  assert.equal(second.getState().streams.size, 0)
})

test('UI projections copy budget counters and ignore delegated events and unknown updates', () => {
  const store = createUiStore()
  const budget = { calls: 2, tokens: 30, cost: 0.01 }
  store.dispatch({ type: 'status', text: 'running', budget })
  budget.tokens = 50
  assert.equal(store.getState().budget.tokens, 30)
  store.dispatch({ type: 'status', text: 'running', budget })
  assert.equal(store.getState().budget.tokens, 50)
  const before = store.getState()
  store.dispatch({ type: 'mode.changed', mode: 'auto', child: 'child' })
  store.dispatch({ type: 'unknown' })
  store.dispatch({ type: 'toString' })
  store.dispatch({ type: 'constructor' })
  store.dispatch({ type: '__proto__' })
  assert.equal(store.getState(), before)
})

test('dialog projections track independent overlays and disposal clears transient data', () => {
  const store = createUiStore()
  store.dispatch({ type: 'ui.dialog.opened', dialog: { id: 'approval', kind: 'approval', callId: 'tool-1' } })
  store.dispatch({ type: 'ui.dialog.opened', dialog: { id: 'language', kind: 'language' } })
  store.dispatch({ type: 'ui.dialog.closed', id: 'approval' })
  assert.deepEqual(store.getState().dialogs.map(dialog => dialog.id), ['language'])
  store.dispatch({ type: 'queued', inputId: 'input', text: 'task' })
  store.dispatch({ type: 'assistant.start', stepId: 'step' })
  store.dispatch({ type: 'ui.closing' })
  store.dispatch({ type: 'ui.closed' })
  assert.equal(store.getState().closing, true)
  assert.equal(store.getState().queued.size, 0)
  assert.equal(store.getState().streams.size, 0)
  assert.deepEqual(store.getState().dialogs, [])
  assert.equal(store.getState().closed, true)
  const closed = store.getState()
  store.dispatch({ type: 'assistant.start', stepId: 'late' })
  store.dispatch({ type: 'ui.language', language: 'zh-CN' })
  store.dispatch({ type: 'ui.dialog.opened', dialog: { id: 'late' } })
  assert.equal(store.getState(), closed)
})

test('unchanged display actions do not notify subscribers while closing still accepts settlement events', () => {
  const store = createUiStore()
  let updates = 0
  const unsubscribe = store.subscribe(() => updates++)
  store.dispatch({ type: 'ui.language', language: 'en' })
  store.dispatch({ type: 'mode.changed', mode: 'ask' })
  store.dispatch({ type: 'ui.dialog.closed', id: 'missing' })
  assert.equal(updates, 0)
  store.dispatch({ type: 'assistant.start', stepId: 'step' })
  store.dispatch({ type: 'ui.closing' })
  store.dispatch({ type: 'ui.closing' })
  assert.equal(updates, 2)
  store.dispatch({ type: 'assistant.end', stepId: 'step' })
  assert.equal(store.getState().streams.size, 0)
  assert.equal(updates, 3)
  unsubscribe()
})

test('failed model streams are discarded and late deltas cannot revive them', () => {
  const store = createUiStore()
  store.dispatch({ type: 'assistant.start', stepId: 'failed' })
  store.dispatch({ type: 'assistant.delta', stepId: 'failed', text: 'Partial' })
  const before = store.getState()
  store.dispatch({ type: 'error', text: 'Connection lost', budget: { calls: 1, tokens: 20, cost: 0 } })
  assert.equal(store.getState().streams.size, 0)
  assert.equal(store.getState().budget.tokens, 20)
  assert.equal(before.streams.get('failed'), 'Partial')
  store.dispatch({ type: 'assistant.delta', stepId: 'failed', text: 'Late' })
  assert.equal(store.getState().streams.size, 0)
  store.dispatch({ type: 'assistant.start', stepId: 'next' })
  store.dispatch({ type: 'assistant.delta', stepId: 'next', text: 'Recovered' })
  assert.equal(store.getState().streams.get('next'), 'Recovered')
})

test('activity tracks parallel tools, clears stale process status, and ignores late output', () => {
  const store = createUiStore()
  store.dispatch({ type: 'status', text: 'running', at: 1000 })
  store.dispatch({ type: 'tool.start', call: { id: 'a', name: 'shell' }, at: 1100 })
  store.dispatch({ type: 'tool.start', call: { id: 'b', name: 'read_file' }, at: 1200 })
  store.dispatch({ type: 'tool.progress', kind: 'process.started', pid: 123, boundary: 'sandbox', at: 1300 })
  store.dispatch({ type: 'tool.end', call: { id: 'a' }, at: 1400 })
  assert.equal(store.getState().activity.phase, 'tools')
  assert.deepEqual(store.getState().activity.tools, { b: 'read_file' })
  store.dispatch({ type: 'tool.end', call: { id: 'b' }, at: 1500 })
  store.dispatch({ type: 'assistant.start', stepId: 'next', at: 1600 })
  assert.equal(store.getState().status, 'running')
  assert.equal(store.getState().activity.phase, 'waiting')
  assert.equal(store.getState().activity.started, 1000)
  store.dispatch({ type: 'assistant.retry', stepId: 'next', at: 1700 })
  assert.equal(store.getState().activity.phase, 'retrying')
  store.dispatch({ type: 'assistant.delta', stepId: 'next', text: 'Hello', at: 1800 })
  assert.equal(store.getState().activity.phase, 'receiving')
  assert.equal(store.getState().activity.lastEvent, 1800)
  store.dispatch({ type: 'error', text: 'Cancelled', at: 1900 })
  store.dispatch({ type: 'assistant.delta', stepId: 'next', text: 'Late', at: 2000 })
  assert.equal(store.getState().activity, null)
})

test('background process state survives tool return and UI inspection without changing an event wait', () => {
  const store = createUiStore()
  const process = { id: 'p-123456abcdef', status: 'running', command: 'build', started: 1000 }
  store.dispatch({ type: 'status', text: 'running' })
  store.dispatch({ type: 'process.state', process, text: 'compiling' })
  const before = store.getState()
  store.dispatch({ type: 'tool.end', call: { id: 'launch' }, status: 'running' })
  assert.equal(store.getState().processes.get(process.id).status, 'running')
  store.dispatch({ type: 'status', text: 'waiting for processes' })
  store.dispatch({ type: 'tool.start', call: { id: 'inspection', name: 'process_status' }, source: 'process-control' })
  store.dispatch({ type: 'tool.end', call: { id: 'inspection' }, source: 'process-control' })
  assert.equal(store.getState().activity.phase, 'waiting for processes')
  store.dispatch({ type: 'process.state', process: { ...process, status: 'completed' }, text: 'done' })
  assert.equal(store.getState().processes.get(process.id).status, 'completed')
  assert.equal(before.processes.get(process.id).status, 'running')
})
